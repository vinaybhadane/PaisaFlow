"""Gemini AI Service with safe deterministic fallbacks.

Handles communication with Google Gemini API using google.generativeai or google.genai,
with prompt injection protections, timeout safeguards, and deterministic rule-based
fallback when the API key is not configured or network requests fail.
"""

from decimal import Decimal
import logging
from typing import Any, Dict, List, Optional
import google.generativeai as genai

from backend.app.core.config import Settings
from backend.app.intelligence.coach.prompts import (
    COACH_SYSTEM_INSTRUCTION,
    COACH_SYSTEM_PROMPT_VERSION,
)

logger = logging.getLogger(__name__)


class GeminiCoachService:
    """Service for generating grounded coach responses using Gemini or deterministic fallbacks."""

    def __init__(self, settings: Optional[Settings] = None):
        self.settings = settings or Settings()
        self.api_key = self.settings.GEMINI_API_KEY
        self.model_name = self.settings.GEMINI_MODEL or "gemini-3.5-flash-lite"
        self._is_configured = bool(self.api_key and self.api_key.strip() and self.api_key != "your_gemini_api_key_here")

        if self._is_configured:
            try:
                genai.configure(api_key=self.api_key)
            except Exception as e:
                logger.warning(f"Failed to configure Gemini SDK: {e}")
                self._is_configured = False

    @property
    def is_configured(self) -> bool:
        """Whether a valid Gemini API key is configured."""
        return self._is_configured

    async def generate_response(
        self,
        user_message: str,
        context_data: Dict[str, Any],
        conversation_history: Optional[List[Dict[str, str]]] = None,
    ) -> Dict[str, Any]:
        """Generate an AI coach response using Gemini if configured, otherwise fallback deterministically.

        Returns a dictionary with:
        - content: markdown response string
        - grounded_facts: list of facts cited
        - assumptions: list of assumptions
        - warnings: list of warnings/disclaimers
        - is_live_gemini: bool
        """
        grounded_facts = context_data.get("grounded_facts", [])
        context_text = context_data.get("context_text", "")

        # Default disclaimers
        warnings = [
            "PaisaFlow is a personal finance coaching demonstration. All figures are based on synthetic demonstration data.",
            "Not certified SEBI financial advice.",
        ]

        if not self._is_configured:
            return self._generate_deterministic_fallback(
                user_message,
                context_data,
                reason="Gemini API key is not configured. Provide GEMINI_API_KEY in .env for live conversational AI.",
                warnings=warnings,
            )

        try:
            # Build prompt with safe XML delimiters for user input
            full_prompt = f"""{context_text}

CONVERSATION CONTEXT:
The user has asked the following question about their financial profile.

<user_question>
{user_message.strip()}
</user_question>

Respond according to the system instructions. Base all numbers strictly on the profile above.
"""

            # Call Gemini
            model = genai.GenerativeModel(
                model_name=self.model_name,
                system_instruction=COACH_SYSTEM_INSTRUCTION,
            )

            # Generate response
            response = await model.generate_content_async(
                full_prompt,
                generation_config=genai.types.GenerationConfig(
                    temperature=0.2,
                    max_output_tokens=1024,
                ),
            )

            if not response or not response.text:
                raise ValueError("Empty response received from Gemini API.")

            return {
                "content": response.text.strip(),
                "grounded_facts": grounded_facts,
                "assumptions": [
                    f"Generated by Gemini ({self.model_name}) based on confirmed financial profile",
                    f"Prompt version: {COACH_SYSTEM_PROMPT_VERSION}",
                ],
                "warnings": warnings,
                "is_live_gemini": True,
            }

        except Exception as exc:
            logger.warning(f"Gemini API invocation failed ({exc}); falling back to deterministic template engine.")
            return self._generate_deterministic_fallback(
                user_message,
                context_data,
                reason=f"Gemini API request failed ({type(exc).__name__}). Using deterministic local financial engine.",
                warnings=warnings,
            )

    def _generate_deterministic_fallback(
        self,
        user_message: str,
        context_data: Dict[str, Any],
        reason: str,
        warnings: List[str],
    ) -> Dict[str, Any]:
        """Generate structured deterministic answers based on exact Decimal aggregates."""
        summary = context_data.get("summary", {})
        top_categories = context_data.get("top_categories", [])
        recurring_list = context_data.get("recurring_list", [])
        total_recurring = context_data.get("total_recurring_monthly", "0.00")
        forecast = context_data.get("forecast")
        insights = context_data.get("insights", [])
        grounded_facts = context_data.get("grounded_facts", [])

        query_lower = user_message.lower()

        # Branch 1: Where is money going / expenses / spending
        if any(w in query_lower for w in ["where", "spend", "expense", "going", "category", "categories"]):
            total_exp = Decimal(str(summary.get("expense_net", "0.00")))
            lines = [
                f"### Spending Analysis for {summary.get('period_start', '')} to {summary.get('period_end', '')}\n",
                f"Your total net spending for this period is **₹{total_exp:,.2f}** across your confirmed transactions.\n",
                "#### Top Spending Categories:",
            ]
            if top_categories:
                for c in top_categories:
                    cat_name = c.get("category_name", "Other")
                    amt = Decimal(str(c.get("amount", 0)))
                    pct = c.get("share_percentage", "0%")
                    lines.append(f"- **{cat_name}**: ₹{amt:,.2f} ({pct} of total expenses)")
            else:
                lines.append("- No categorized expenses recorded for this period.")

            if insights:
                lines.append(f"\n💡 **Key Observation:** {insights[0].title} — {insights[0].explanation}")

            lines.append("\n**Actionable Suggestion:** Look closely at your top 2 categories to find discretionary expenses that can be reduced or capped with a monthly budget.")
            content = "\n".join(lines)

        # Branch 2: Recurring payments / subscriptions
        elif any(w in query_lower for w in ["recurring", "subscription", "bill", "commit", "cadence"]):
            lines = [
                "### Active Recurring Commitments & Subscriptions\n",
                f"You currently have **{len(recurring_list)} detected recurring commitments**, totaling an estimated **₹{Decimal(total_recurring):,.2f} per month**.\n",
                "#### Breakdown of Commitments:",
            ]
            if recurring_list:
                for r in recurring_list:
                    lines.append(f"- **{r['merchant']}**: {r['amount']} ({r['cadence']}) — Monthly equivalent: {r['monthly_equivalent']}")
            else:
                lines.append("- No recurring payments or subscriptions detected yet.")

            lines.append("\n**Actionable Suggestion:** Review any streaming or software subscriptions you haven't actively used in the last 30 days.")
            content = "\n".join(lines)

        # Branch 3: Affordability / EMI / Loan / Purchase
        elif any(w in query_lower for w in ["afford", "emi", "buy", "loan", "purchase", "new car", "new phone"]):
            net_surplus = Decimal(str(summary.get("net_cash_flow", "0.00")))
            income = Decimal(str(summary.get("income_total", "0.00")))
            savings_rate = summary.get("savings_rate", "0%")

            lines = [
                "### Affordability & Cash Flow Analysis\n",
                f"Based on your current month's performance, your net cash flow surplus is **₹{net_surplus:,.2f}** with an income of **₹{income:,.2f}** (Savings Rate: **{savings_rate}**).\n",
            ]
            if net_surplus > Decimal("10000"):
                lines.append("✅ **Cash Flow Verdict:** Your current net surplus indicates positive cash flow cushion to absorb a moderate new monthly obligation.")
                lines.append("- Ensure that total EMIs and fixed commitments do not exceed **40%** of your monthly income.")
                lines.append("- Maintain at least 3 to 6 months of living expenses in an emergency fund before locking into long-term commitments.")
            elif net_surplus > Decimal("0"):
                lines.append("⚠️ **Caution Advised:** You have a small positive surplus, but taking on additional fixed EMIs could reduce your savings margin to zero if variable expenses spike.")
            else:
                lines.append("❌ **High Risk:** Your current expenses exceed your income in this period. Adding a new fixed EMI is strongly discouraged until spending is reconciled.")

            content = "\n".join(lines)

        # Branch 4: Savings rate / How to save more
        elif any(w in query_lower for w in ["saving", "save", "invest", "surplus"]):
            income = Decimal(str(summary.get("income_total", "0.00")))
            expenses = Decimal(str(summary.get("expense_net", "0.00")))
            net_surplus = Decimal(str(summary.get("net_cash_flow", "0.00")))
            savings_rate = summary.get("savings_rate", "0%")

            lines = [
                "### Savings Strategy & Target Review\n",
                f"- **Total Inflow:** ₹{income:,.2f}\n"
                f"- **Total Outflow:** ₹{expenses:,.2f}\n"
                f"- **Net Monthly Surplus:** ₹{net_surplus:,.2f}\n"
                f"- **Current Savings Rate:** **{savings_rate}**\n",
                "#### Recommendations to Boost Savings:",
                "1. **Audit Recurring Outflows:** Review your active subscriptions to eliminate unused recurring services.",
                "2. **Target Discretionary Spikes:** Check categories like Dining & Entertainment which often account for unexpected monthly budget leakages.",
                "3. **Automate Transfers:** Set up an automatic sweep or SIP on the day after salary credit to ensure savings happen first.",
            ]
            content = "\n".join(lines)

        # Branch 5: Forecast / Future trajectory
        elif any(w in query_lower for w in ["forecast", "future", "next month", "3 month", "projection"]):
            lines = [
                "### 3-Month Deterministic Financial Forecast\n",
                f"- **Baseline Monthly Inflow:** ₹{forecast.baseline_monthly_income:,.2f}\n"
                f"- **Baseline Monthly Expenses:** ₹{forecast.baseline_monthly_expenses:,.2f}\n"
                f"- **Baseline Net Cash Flow:** ₹{forecast.baseline_net_cash_flow:,.2f}\n\n"
                "#### Month-by-Month Projection:",
            ]
            if forecast and hasattr(forecast, "months"):
                for m in forecast.months:
                    lines.append(f"- **Month {m.month_index} ({m.target_month_label})**: Expected Net **₹{m.projected_net_cash_flow:,.2f}**, Projected Cumulative Savings: **₹{m.projected_cumulative_savings:,.2f}**")
            lines.append("\n*Note: Projections assume current recurring obligations and historical spending averages continue without disruption.*")
            content = "\n".join(lines)

        # Default: General financial overview
        else:
            income = Decimal(str(summary.get("income_total", "0.00")))
            expenses = Decimal(str(summary.get("expense_net", "0.00")))
            net_surplus = Decimal(str(summary.get("net_cash_flow", "0.00")))
            savings_rate = summary.get("savings_rate", "0%")

            lines = [
                "### Financial Overview & Living Money Profile\n",
                f"Here is your current financial standing for {summary.get('period_start', '')} to {summary.get('period_end', '')}:\n",
                f"- **Monthly Inflow (Income):** ₹{income:,.2f}",
                f"- **Monthly Outflow (Expenses):** ₹{expenses:,.2f}",
                f"- **Net Surplus Cash Flow:** ₹{net_surplus:,.2f}",
                f"- **Savings Rate:** {savings_rate}",
                f"- **Active Recurring Commitments:** {len(recurring_list)} commitments (~₹{Decimal(total_recurring):,.2f}/month)\n",
            ]
            if top_categories:
                lines.append("#### Top Expense Areas:")
                for c in top_categories[:3]:
                    lines.append(f"- {c.get('category_name')}: ₹{Decimal(str(c.get('amount', 0))):,.2f}")

            lines.append("\nYou can ask me specific questions like *'Where is most of my money going?'*, *'Can I afford a new ₹5,000 EMI?'*, or *'How can I improve my savings rate?'*.")
            content = "\n".join(lines)

        return {
            "content": content,
            "grounded_facts": grounded_facts,
            "assumptions": [
                f"PaisaFlow Deterministic Financial Engine ({reason})",
                "Calculations performed with 100% Python Decimal precision",
            ],
            "warnings": warnings,
            "is_live_gemini": False,
        }
